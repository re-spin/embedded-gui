"""Regenerate src/fonts.rs: embedded-graphics 0.8 ASCII raw sheets (1bpp, 16
glyphs per row, ' '..) -> embedded-gui BitmapFont rows (MSB left).

Usage: python3 spikes/bfin/gen_font.py ~/.cargo/registry/src/*/embedded-graphics-0.8.1/fonts/raw/ascii
"""
import sys
from pathlib import Path

FONTS = [("ROW", "font_9x18_bold.raw", 9, 18), ("SMALL", "font_6x10.raw", 6, 10), ("PANE", "font_7x13.raw", 7, 13)]


def main():
    src = Path(sys.argv[1])
    out = ["// @generated by gen_font.py from embedded-graphics 0.8 ASCII raw fonts.",
           "use embedded_gui::BitmapFont;", ""]
    for name, file, w, h in FONTS:
        raw = (src / file).read_bytes()
        stride = 16 * w // 8
        bpr = (w + 7) // 8
        glyphs = []
        for g in range(95):  # ' '..='~'
            gx, gy = g % 16 * w, g // 16 * h
            for y in range(h):
                bits = 0
                for x in range(w):
                    px = gx + x
                    if raw[(gy + y) * stride + px // 8] & (0x80 >> (px % 8)):
                        bits |= 1 << (bpr * 8 - 1 - x)
                glyphs += list(bits.to_bytes(bpr, "big"))
        out.append(f"static {name}_GLYPHS: [u8; {len(glyphs)}] = {glyphs};")
        out.append(f"pub static {name}: BitmapFont = BitmapFont {{ width: {w}, height: {h}, advance: {w}, "
                   f"line_height: {h}, first_char: 32, bytes_per_row: {bpr}, glyphs: &{name}_GLYPHS }};")
        out.append("")
    Path(__file__).with_name("src").joinpath("fonts.rs").write_text("\n".join(out))


if __name__ == "__main__":
    main()
